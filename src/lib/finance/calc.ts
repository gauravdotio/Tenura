export interface PlanProgress {
  paidCount: number;
  totalCount: number;
  paidAmount: number;
  remainingAmount: number;
  percent: number;
  nextDue?: Installment;
  lastMonth?: string;
}

export function planProgress(installments: Installment[]): PlanProgress {
  let paidCount = 0;
  let paidAmount = 0;
  let remainingAmount = 0;
  let nextDue: Installment | undefined;
  for (const i of installments) {
    if (i.paidOn) {
      paidCount++;
      paidAmount += i.amount;
    } else {
      remainingAmount += i.amount;
      if (!nextDue || i.seq < nextDue.seq) nextDue = i;
    }
  }
  const totalCount = installments.length;
  return {
    paidCount,
    totalCount,
    paidAmount,
    remainingAmount,
    percent: totalCount ? Math.round((paidCount / totalCount) * 100) : 0,
    nextDue,
    lastMonth: installments.reduce<string | undefined>((m, i) => (!m || i.dueMonth > m ? i.dueMonth : m), undefined),
  };
}

/** What is still owed: unpaid installments for a plan, otherwise the balance. Closed = 0. */
export function outstandingFor(l: Liability, installments: Installment[]): number {
  if (l.status === 'closed') return 0;
  if (installments.length > 0) return planProgress(installments).remainingAmount;
  return l.balance;
}

export function groupInstallments(installments: Installment[]): Map<string, Installment[]> {
  const map = new Map<string, Installment[]>();
  for (const i of installments) {
    const list = map.get(i.liabilityId);
    if (list) list.push(i);
    else map.set(i.liabilityId, [i]);
  }
  for (const list of map.values()) list.sort((a, b) => a.seq - b.seq);
  return map;
}

