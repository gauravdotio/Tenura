export interface Summary {
  /** Everything still owed across open liabilities. */
  outstanding: number;
  creditCardOutstanding: number;
  loanOutstanding: number;
  /** EMIs falling due each month across active plans + loans with an EMI. */
  monthlyEmi: number;
  /** Insurance premiums spread per month. */
  monthlyPremiums: number;
  /** Already repaid: paid installments + settled liabilities without a plan. */
  repaid: number;
  openCount: number;
  activePlanCount: number;
  closedCount: number;
  spentThisMonth: number;
  monthlyBudget: number;
  sumAssured: number;
  /** Last month any active plan has an unpaid installment. */
  debtFreeMonth?: string;
}

export function summarize(data: FinanceData, today: Date = new Date()): Summary {
  const byLiability = groupInstallments(data.installments);
  const thisMonth = toMonthKey(today);
  const s: Summary = {
    outstanding: 0,
    creditCardOutstanding: 0,
    loanOutstanding: 0,
    monthlyEmi: 0,
    monthlyPremiums: 0,
    repaid: 0,
    openCount: 0,
    activePlanCount: 0,
    closedCount: 0,
    spentThisMonth: 0,
    monthlyBudget: data.members.reduce((sum, m) => sum + (m.monthlyBudget || 0), 0),
    sumAssured: 0,
  };

  for (const l of data.liabilities) {
    const inst = byLiability.get(l.id) ?? [];
    const progress = planProgress(inst);
    s.repaid += progress.paidAmount;

    if (l.status === 'closed') {
      s.closedCount++;
      if (inst.length === 0) s.repaid += l.balance;
      continue;
    }

    const owed = outstandingFor(l, inst);
    s.outstanding += owed;
    s.openCount++;
    if (l.kind === 'credit_card' && l.status === 'active') s.creditCardOutstanding += owed;
    else s.loanOutstanding += owed;

    if (inst.length > 0 && progress.remainingAmount > 0) {
      s.activePlanCount++;
      s.monthlyEmi += progress.nextDue?.amount ?? l.emiAmount ?? 0;
      const lastUnpaid = inst.filter((i) => !i.paidOn).at(-1)?.dueMonth;
      if (lastUnpaid && (!s.debtFreeMonth || lastUnpaid > s.debtFreeMonth)) s.debtFreeMonth = lastUnpaid;
    }
  }

  for (const e of data.expenses) {
    if (e.date.startsWith(thisMonth)) s.spentThisMonth += e.amount;
  }
  for (const p of data.policies) {
    s.monthlyPremiums += annualPremium(p) / 12;
    if (p.status === 'active') s.sumAssured += p.sumAssured;
  }
  s.monthlyPremiums = Math.round(s.monthlyPremiums);
  return s;
}

