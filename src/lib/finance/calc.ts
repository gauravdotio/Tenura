// ---------------------------------------------------------------------------
// EMI maths
// ---------------------------------------------------------------------------

/**
 * Standard reducing-balance EMI: P·r·(1+r)^n / ((1+r)^n − 1), r = monthly rate.
 * A 0% rate (no-cost EMI) splits the principal evenly. Rounded to the rupee.
 */
export function calculateEmi(principal: number, annualRatePct: number, months: number): number {
  if (principal <= 0 || months <= 0) return 0;
  const r = annualRatePct / 12 / 100;
  if (r === 0) return Math.round(principal / months);
  const f = Math.pow(1 + r, months);
  return Math.round((principal * r * f) / (f - 1));
}

export function emiBreakdown(principal: number, annualRatePct: number, months: number) {
  const emi = calculateEmi(principal, annualRatePct, months);
  const totalPayable = emi * months;
  return { emi, totalPayable, totalInterest: Math.max(0, totalPayable - principal) };
}

/** Month-by-month installments for a plan. Ids are generated by `makeId`. */
export function buildInstallments(
  liabilityId: string,
  emiAmount: number,
  tenureMonths: number,
  startMonth: string,
  makeId: () => string,
): Installment[] {
  return Array.from({ length: tenureMonths }, (_, i) => ({
    id: makeId(),
    liabilityId,
    seq: i + 1,
    dueMonth: addMonthsToKey(startMonth, i),
    amount: emiAmount,
  }));
}

export function hasPlan(l: Pick<Liability, 'emiAmount' | 'tenureMonths'>): boolean {
  return Boolean(l.emiAmount && l.emiAmount > 0 && l.tenureMonths && l.tenureMonths > 0);
}

