export type DueItem =
  | { kind: 'installment'; key: string; date: string; days: number; amount: number; title: string; subtitle: string; memberId: string; liabilityId: string; installmentId: string }
  | { kind: 'card'; key: string; date: string; days: number; amount: number; title: string; subtitle: string; memberId: string; liabilityId: string }
  | { kind: 'premium'; key: string; date: string; days: number; amount: number; title: string; subtitle: string; memberId: string; policyId: string };

/** Installments are treated as due on the 5th unless the liability has a due day. */
export const DEFAULT_EMI_DAY = 5;

/**
 * Everything unpaid that is overdue or due within `horizonDays`, soonest first.
 * Only the earliest unpaid installment of each plan is listed, so a plan
 * never floods the list.
 */
export function upcomingPayments(data: FinanceData, todayIso: string, horizonDays = 30): DueItem[] {
  const items: DueItem[] = [];
  const byLiability = groupInstallments(data.installments);

  for (const l of data.liabilities) {
    if (l.status === 'closed') continue;
    const inst = byLiability.get(l.id) ?? [];
    const label = l.cardLast4 ? `${l.provider} ··${l.cardLast4}` : l.provider;

    if (inst.length > 0) {
      const next = planProgress(inst).nextDue;
      if (!next) continue;
      const date = dateInMonth(next.dueMonth, l.dueDay ?? DEFAULT_EMI_DAY);
      items.push({
        kind: 'installment',
        key: `i-${next.id}`,
        date,
        days: daysBetween(todayIso, date),
        amount: next.amount,
        title: label,
        subtitle: `EMI ${next.seq} of ${inst.length}`,
        memberId: l.memberId,
        liabilityId: l.id,
        installmentId: next.id,
      });
    } else if (l.kind === 'credit_card' && l.balance > 0 && l.dueDay) {
      const thisMonth = todayIso.slice(0, 7);
      let date = dateInMonth(thisMonth, l.dueDay);
      // A bill whose day has passed this month is shown for next month: we only
      // know the balance, not whether this month's statement was already paid.
      if (date < todayIso) date = dateInMonth(addMonthsToKey(thisMonth, 1), l.dueDay);
      items.push({
        kind: 'card',
        key: `c-${l.id}`,
        date,
        days: daysBetween(todayIso, date),
        amount: l.balance,
        title: label,
        subtitle: 'Card bill',
        memberId: l.memberId,
        liabilityId: l.id,
      });
    }
  }

  for (const p of data.policies) {
    if (p.status !== 'active' || !p.nextDueDate) continue;
    items.push({
      kind: 'premium',
      key: `p-${p.id}`,
      date: p.nextDueDate,
      days: daysBetween(todayIso, p.nextDueDate),
      amount: p.premium,
      title: p.name,
      subtitle: `${p.provider} premium`,
      memberId: p.memberId,
      policyId: p.id,
    });
  }

  return items
    .filter((i) => i.days <= horizonDays)
    .sort((a, b) => a.date.localeCompare(b.date) || b.amount - a.amount);
}

