export interface MonthOutflow {
  month: string;
  emi: number;
  premiums: number;
}

/** Scheduled EMI + premium outflow for the next `months` months, starting this month. */
export function projectOutflow(data: FinanceData, today: Date, months = 12): MonthOutflow[] {
  const start = toMonthKey(today);
  const rows: MonthOutflow[] = Array.from({ length: months }, (_, i) => ({
    month: addMonthsToKey(start, i),
    emi: 0,
    premiums: 0,
  }));
  const index = new Map(rows.map((r, i) => [r.month, i]));
  const open = new Set(data.liabilities.filter((l) => l.status !== 'closed').map((l) => l.id));

  for (const i of data.installments) {
    if (i.paidOn || !open.has(i.liabilityId)) continue;
    // Overdue installments are still owed — count them in the current month
    const at = i.dueMonth < start ? 0 : index.get(i.dueMonth);
    if (at !== undefined) rows[at].emi += i.amount;
  }

  for (const p of data.policies) {
    if (p.status !== 'active' || !p.nextDueDate) continue;
    const step = MONTHS_BETWEEN_PREMIUMS[p.frequency];
    let due = p.nextDueDate.slice(0, 7);
    if (due < start) due = start;
    for (let k = 0; k < months; k += 1) {
      const at = index.get(due);
      if (at === undefined) break;
      rows[at].premiums += p.premium;
      due = addMonthsToKey(due, step);
    }
  }
  return rows;
}

/** Outstanding balance at the end of each of the next `months` months if every EMI is paid on schedule. */
export function projectBurndown(data: FinanceData, today: Date, months = 12) {
  const start = toMonthKey(today);
  const byLiability = groupInstallments(data.installments);
  let balance = 0;
  const scheduled: number[] = Array(months).fill(0);

  for (const l of data.liabilities) {
    const inst = byLiability.get(l.id) ?? [];
    balance += outstandingFor(l, inst);
    if (l.status === 'closed') continue;
    for (const i of inst) {
      if (i.paidOn) continue;
      const offset = i.dueMonth < start ? 0 : monthsBetween(start, i.dueMonth);
      if (offset < months) scheduled[offset] += i.amount;
    }
  }

  const rows = [{ month: start, balance }];
  let running = balance;
  for (let k = 0; k < months; k++) {
    running = Math.max(0, running - scheduled[k]);
    rows.push({ month: addMonthsToKey(start, k + 1), balance: running });
  }
  return rows;
}

function monthsBetween(from: string, to: string): number {
  const [fy, fm] = from.split('-').map(Number);
  const [ty, tm] = to.split('-').map(Number);
  return (ty - fy) * 12 + (tm - fm);
}

export function spendingByCategory(expenses: Expense[], monthKey: string) {
  const totals = new Map<string, number>();
  for (const e of expenses) {
    if (!e.date.startsWith(monthKey)) continue;
    totals.set(e.category, (totals.get(e.category) ?? 0) + e.amount);
  }
  return [...totals.entries()].map(([category, amount]) => ({ category, amount })).sort((a, b) => b.amount - a.amount);
}

export function memberById(members: Member[]): Map<string, Member> {
  return new Map(members.map((m) => [m.id, m]));
}

