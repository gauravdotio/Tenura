export const PAYMENTS_PER_YEAR: Record<PremiumFrequency, number> = {
  monthly: 12,
  quarterly: 4,
  half_yearly: 2,
  yearly: 1,
};

export const MONTHS_BETWEEN_PREMIUMS: Record<PremiumFrequency, number> = {
  monthly: 1,
  quarterly: 3,
  half_yearly: 6,
  yearly: 12,
};

export function annualPremium(p: Policy): number {
  return p.status === 'active' ? p.premium * PAYMENTS_PER_YEAR[p.frequency] : 0;
}

export function nextPremiumDateAfterPayment(p: Policy): string | undefined {
  return p.nextDueDate ? addMonthsToDate(p.nextDueDate, MONTHS_BETWEEN_PREMIUMS[p.frequency]) : undefined;
}

